"""A procedurally generated neighbourhood for developing the browser app without real data.

The layout loosely mimics a Victorian terraced area: an east-west street grid with
cambered carriageways and raised pavements, rows of terraced houses with back
gardens, a park, and a low spot under a junction where surface water will pond.
"""

from __future__ import annotations

import numpy as np

from .scene import LandCover, Scene

# A plausible spot in OSGB36 / British National Grid so coordinates look realistic.
DEFAULT_ORIGIN = (471_000.0, 173_400.0)


def make_synthetic_scene(size_m: float = 400.0, cell_size: float = 1.0, seed: int = 7) -> Scene:
    rng = np.random.default_rng(seed)
    n = round(size_m / cell_size)
    # Cell centre coordinates in metres: x increases east, y increases south.
    y, x = (np.mgrid[0:n, 0:n].astype(np.float32) + 0.5) * cell_size

    # Ground rises gently to the south and east, with low undulations.
    ground = (
        40.0
        + 0.012 * y
        + 0.004 * x
        + 0.6 * np.sin(x / 70.0) * np.cos(y / 55.0)
        + 0.3 * np.sin((x + y) / 31.0)
    )
    # A dip under one junction, like a railway underpass: the obvious ponding hotspot.
    dip_x, dip_y = 0.55 * size_m, 0.5 * size_m
    ground -= 1.8 * np.exp(-((x - dip_x) ** 2 + (y - dip_y) ** 2) / (2 * 18.0**2))

    land_cover = np.full((n, n), LandCover.OTHER, dtype=np.uint8)
    building_height = np.zeros((n, n), dtype=np.float32)

    street_pitch_y, street_pitch_x = 80.0, 130.0
    carriageway, pavement = 7.0, 2.0
    half_road = carriageway / 2 + pavement

    # Distance to the nearest street centreline in each direction.
    dy = np.abs((y - street_pitch_y / 2) % street_pitch_y - street_pitch_y / 2)
    dx = np.abs((x - street_pitch_x / 2) % street_pitch_x - street_pitch_x / 2)
    road_dist = np.minimum(dy, dx)
    is_road = road_dist <= half_road
    is_carriageway = road_dist <= carriageway / 2

    # Kerbs: the carriageway sits 12 cm below the pavement, with a slight camber.
    camber = 0.04 * (road_dist / (carriageway / 2)) ** 2
    ground = np.where(is_carriageway, ground - 0.12 - 0.04 + camber, ground)
    land_cover[is_road] = LandCover.PAVED

    # Terraces: one row of houses each side of every east-west street, set back
    # behind a small front garden, 9 m deep, broken by alleys every ~40 m.
    front_garden, house_depth, house_width = 2.0, 9.0, 5.0
    in_terrace_band = (dy > half_road + front_garden) & (
        dy <= half_road + front_garden + house_depth
    )
    alley = (x % 40.0) < 1.5
    in_terrace = in_terrace_band & ~alley & (dx > half_road + 1.0)

    # Each house gets its own roof height so the skyline is not flat.
    house_ids = (np.floor(x / house_width) + 1000 * np.floor(y / (street_pitch_y / 2))).astype(int)
    unique_ids, inverse = np.unique(house_ids, return_inverse=True)
    heights = rng.uniform(6.5, 9.0, size=unique_ids.size).astype(np.float32)
    house_height = heights[inverse.reshape(n, n)]
    building_height = np.where(in_terrace, house_height, 0.0).astype(np.float32)
    land_cover[in_terrace] = LandCover.BUILDING

    # A park fills one block in the north-east: grass with a few tree clumps.
    block_x = np.floor((x + street_pitch_x / 2) / street_pitch_x)
    block_y = np.floor((y + street_pitch_y / 2) / street_pitch_y)
    park = (block_x == 2) & (block_y == 1) & ~is_road
    land_cover[park] = LandCover.GRASS
    building_height[park] = 0.0
    for _ in range(6):
        cx, cy = (
            rng.uniform(2.0 * street_pitch_x - 40, 2.0 * street_pitch_x + 40),
            rng.uniform(street_pitch_y - 25, street_pitch_y + 25),
        )
        clump = park & ((x - cx) ** 2 + (y - cy) ** 2 < rng.uniform(25, 80))
        land_cover[clump] = LandCover.TREES

    ox, oy = DEFAULT_ORIGIN
    return Scene(
        name="Synthetic neighbourhood",
        cell_size=cell_size,
        origin_x=ox,
        origin_y=oy,
        crs="EPSG:27700",
        ground=ground,
        building_height=building_height,
        land_cover=land_cover,
        attribution=["Synthetic data generated by wsim-prep"],
    )
